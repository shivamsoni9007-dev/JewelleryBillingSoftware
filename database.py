def update_setting(
    key,
    value
):

    conn = get_db_connection()

    existing = conn.execute("""
        SELECT id

        FROM app_settings

        WHERE setting_key = ?
    """, (
        key,
    )).fetchone()


    if existing:

        conn.execute("""
            UPDATE app_settings

            SET
                setting_value = ?,
                updated_at = CURRENT_TIMESTAMP

            WHERE setting_key = ?
        """, (
            value,
            key
        ))

    else:

        conn.execute("""
            INSERT INTO app_settings (
                setting_key,
                setting_value
            )

            VALUES (?, ?)
        """, (
            key,
            value
        ))


    conn.commit()
    conn.close()



