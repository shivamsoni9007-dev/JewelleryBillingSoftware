def get_all_settings():

    conn = get_db_connection()

    rows = conn.execute("""
        SELECT
            setting_key,
            setting_value

        FROM app_settings
    """).fetchall()

    conn.close()

    settings = {}

    for row in rows:

        settings[
            row["setting_key"]
        ] = (
            row["setting_value"]
            or ""
        )

    return settings



